for (const [region, settlements] of Object.entries(REGION_SETTLEMENTS)) {
  for (const settlement of settlements) {
    const key = settlement.toLowerCase().replace(/^(селище|село|м\.|смт)\s+/i, "").trim();
    if (!CITY_REGION_MAP[key]) CITY_REGION_MAP[key] = region;
    CITY_REGION_MAP[settlement.toLowerCase()] = region;
  }
}

export function normalizeRegionName(raw) {
  const text = String(raw || "").trim();
  if (!text) return "";
  const cleaned = text
    .replace(/\s+область$/i, "")
    .replace(/\s+обл\.?$/i, "")
    .trim();
  for (const region of UKRAINIAN_REGIONS) {
    if (region.toLowerCase() === cleaned.toLowerCase() || region.toLowerCase() === text.toLowerCase()) {
      return region;
    }
  }
  return cleaned;
}

export function formatRegionOptionLabel(region) {
  if (!region || region === "Всі") return "Всі області України";
  if (region === "Автономна Республіка Крим") return region;
  return `${region} область`;
}

export function inferRegionForCity(city) {
  if (!city) return "";
  const raw = String(city).trim().toLowerCase();
  const stripped = raw.replace(/^(селище|село|м\.|смт)\s+/i, "").trim();
  return CITY_REGION_MAP[raw] || CITY_REGION_MAP[stripped] || "";
}

export function getSettlementsForRegion(region) {
  const norm = normalizeRegionName(region);
  return REGION_SETTLEMENTS[norm] || [];
}

export function getAllSettlements() {
  const set = new Set();
  for (const list of Object.values(REGION_SETTLEMENTS)) {
    for (const item of list) set.add(item);
  }
  return Array.from(set).sort((a, b) => a.localeCompare(b, "uk"));
}

export function isCityInRegion(city, region) {
  if (!region || region === "Всі") return true;
  if (!city) return false;
  const normRegion = normalizeRegionName(region);
  const inferred = inferRegionForCity(city);
  if (inferred && inferred.toLowerCase() === normRegion.toLowerCase()) return true;
  const list = REGION_SETTLEMENTS[normRegion];
  if (!list) return false;
  const target = String(city).trim().toLowerCase();
  return list.some((item) => item.toLowerCase() === target || item.toLowerCase().includes(target));
}
